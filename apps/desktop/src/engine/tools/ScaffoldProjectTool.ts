import fs from "fs";
import path from "path";
import { z } from "zod";
import { DesktopTool, ExecutionContext, ToolResult } from "./DesktopTool";

const scaffoldProjectSchema = z.object({
  targetDirectory: z.string().optional().default("Projects"),
  projectName: z.string().min(1, "Project name is required"),
  template: z.enum(["portfolio", "web_app", "documentation", "static_site"]).default("portfolio"),
  projectData: z.record(z.string(), z.any()).optional(),
});

export class ScaffoldProjectTool implements DesktopTool {
  public readonly name = "scaffold_project";
  public readonly description = "Safely creates a structured website or application skeleton inside an allowed directory";
  public readonly inputSchema = scaffoldProjectSchema;
  public readonly requiresApproval = true;

  public async execute(input: z.infer<typeof scaffoldProjectSchema>, context: ExecutionContext): Promise<ToolResult> {
    if (context.signal?.aborted) {
      return { success: false, error: "Operation cancelled by user", metadata: { code: "CANCELLED" } };
    }

    const { targetDirectory, projectName, template, projectData } = input;
    const fileSystem = context.fileSystem;

    // Resolve target path
    let resolvedDir = targetDirectory;
    const namedDir = fileSystem.findAllowedDirectoryByName(resolvedDir);
    if (namedDir) {
      resolvedDir = namedDir.path;
    } else if (!path.isAbsolute(resolvedDir)) {
      const defaultDir = fileSystem.getDefaultAllowedDirectory();
      if (!defaultDir) {
        return { success: false, error: "No allowed directory configured", metadata: { code: "DIR_NOT_CONFIGURED" } };
      }
      resolvedDir = path.join(defaultDir.path, resolvedDir);
    }

    const projectFullPath = path.join(resolvedDir, projectName);

    // Validate write permission
    const val = fileSystem.validatePath(projectFullPath, "write");
    if (!val.allowed || !val.normalizedPath) {
      return { success: false, error: val.error || "Write access denied to target directory", metadata: { code: "ACCESS_DENIED" } };
    }

    const dest = val.normalizedPath;
    fs.mkdirSync(dest, { recursive: true });

    context.onProgress?.("SCAFFOLDING", `Creating ${template} structure in ${projectName}...`, 30);

    // Create standard static portfolio files safely
    const indexHtmlContent = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${projectName} - Portfolio</title>
  <style>
    :root { --bg: #0d1117; --text: #c9d1d9; --accent: #58a6ff; }
    body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; background: var(--bg); color: var(--text); padding: 2rem; max-width: 900px; margin: auto; }
    h1 { color: #f0f6fc; }
    .project-card { border: 1px solid #30363d; border-radius: 8px; padding: 1rem; margin-bottom: 1rem; background: #161b22; }
    .tag { display: inline-block; background: #1f6feb26; color: #58a6ff; padding: 2px 8px; border-radius: 4px; font-size: 0.85rem; }
  </style>
</head>
<body>
  <h1>${projectName}</h1>
  <p>Generated by Agent Anjaneya Autonomous System.</p>
  <h2>Projects</h2>
  <div class="project-card">
    <h3>Portfolio Highlights</h3>
    <p>Curated and packaged autonomously based on desktop project analysis.</p>
    <span class="tag">Production Ready</span>
  </div>
</body>
</html>`;

    const portfolioJsonContent = JSON.stringify(
      {
        name: projectName,
        template,
        createdAt: new Date().toISOString(),
        metadata: projectData || {},
        status: "GENERATED",
      },
      null,
      2
    );

    fs.writeFileSync(path.join(dest, "index.html"), indexHtmlContent, "utf-8");
    fs.writeFileSync(path.join(dest, "portfolio.json"), portfolioJsonContent, "utf-8");

    const outputPath = path.join(dest, "index.html");
    const stats = fs.statSync(outputPath);

    context.onProgress?.("SCAFFOLDED", `Portfolio created at ${outputPath}`, 100);

    return {
      success: true,
      data: {
        outputPath,
        projectDirectory: dest,
        projectName,
        template,
        sizeBytes: stats.size,
        filesCreated: ["index.html", "portfolio.json"],
      },
    };
  }
}
